/// Claude アプリ（無料プラン）に渡して、議事録の形の要約を作ってもらうための文章。
///
/// API を使わないのでお金はかからない。共有ボタンでこの文章を Claude アプリに送り、
/// 返ってきた要約をコピーしてアプリに貼り付けて保存する。
class LectureNotePrompt {
  static const instructions = '''
あなたは会議の議事録を作る優秀なアシスタントです。
下にあるのは会議を音声認識で文字起こししたテキストです。聞き間違いや言い直しが含まれるので、文脈から正しい内容を推測して整理してください。
「話者1：」「田中：」のように行の頭にある名前は、その発言をした人です。名前が無い行は、直前と同じ人の発言です。
参加者があとで読み返したり、欠席した人に共有したりすることを想定し、日本語で次の形式の議事録を書いてください。

【会議の概要】
2〜4文で、何について話し合い、どうなったかを説明する。

【決定事項】
・会議で決まったことを箇条書きにする。決まったことが無ければ「なし」と書く。

【やること】
・内容（担当：名前、期限：日付）の形で書く。担当や期限が話されていなければ「未定」と書く。

【話し合った内容】
・議題ごとに、主な意見と誰が言ったかを箇条書きにする。

【次回までの課題・保留事項】
・結論が出なかったことや、次回に持ち越したこと。無ければ「なし」と書く。

ルール:
・見出しは【】、箇条書きは「・」を使う。Markdown の記号（#、*、**）は使わない。
・文字起こしに無い内容を作り足さない。不明な部分は「（聞き取り不明）」と書く。
''';

  static String build({required String title, required String transcript}) =>
      '$instructions\n会議名: $title\n\n<transcript>\n$transcript\n</transcript>\n\n'
      'この会議の議事録を作ってください。';
}
